  function plan() {
    step(T("plan.step")); app.classList.add("compact");
    if (!S.content) { panel.innerHTML = `<h2>${esc(T("plan.errTitle"))}</h2><p>${esc(T("plan.errText"))}</p>`; return; }
    if (!S.suggested) { S.picks = suggest(); S.suggested = true; } // only once per round, so "Clear" really clears
    const all = S.content.ideas.map((i) => i.chapter), unplayed = all.filter((c) => !S.played.has(c));
    const rows = [...S.content.ideas].sort((a, b) => a.chapter - b.chapter).map((i) => {
      const on = S.picks.includes(i.chapter), w = tx(i);
      return `<li class="habit ${on ? "on" : ""}" data-ch="${i.chapter}">
        <button class="pick" aria-pressed="${on}"><span class="check">${on ? "✓" : ""}</span>${icon(i.icon)}<span>${esc(w.name)}${S.played.has(i.chapter) ? `<span class="played">${esc(T("plan.played"))}</span>` : ""}</span></button>
        <span class="rank" title="${esc(T("plan.rank"))}">#${i.reader.rank}</span><i class="dot ${i.light}" title="${esc(LIGHT(i.light))}"></i>
        <button class="info" data-receipt="${i.chapter}" aria-label="${esc(T("plan.sourcesFor", { name: w.name }))}">i</button>
      </li>`;
    }).join("");
    const n = S.picks.length, moments = n * perHabit();
    const head = !S.played.size ? T("plan.picked") : unplayed.length ? T("plan.playedSome", { n: S.played.size }) : T("plan.playedAll", { n: all.length });
    panel.innerHTML = `
      <span class="label">${esc(head + T("plan.change"))}</span>
      <h2>${esc(T("plan.title"))}</h2>
      <div class="tools">
        <button class="chip" id="all" aria-pressed="${n === all.length}">${esc(T("plan.all"))}</button>
        ${S.played.size && unplayed.length ? `<button class="chip" id="unplayed">${esc(T("plan.unplayed"))}</button>` : ""}
        <button class="chip" id="none">${esc(T("plan.clear"))}</button>
      </div>
      <ul class="habits">${rows}</ul>
      <p class="small">${esc(T("plan.legend"))}<br><i class="dot GREEN"></i> ${esc(T("plan.keyGreen"))} · <i class="dot AMBER"></i> ${esc(T("plan.keyAmber"))} · <i class="dot RED"></i> ${esc(T("plan.keyRed"))} · <i class="dot GREY"></i> ${esc(T("plan.keyGrey"))}</p>
      <div class="sticky"><button class="btn solid wide" id="launch" ${n ? "" : "disabled"}>${esc(n ? T("plan.start", { m: moments, k: perHabit() }) : T("plan.none"))}</button></div>`;
    const redraw = () => { const st = panel.scrollTop; plan(); panel.scrollTop = st; };
    panel.querySelectorAll(".habit .pick").forEach((b) => b.addEventListener("click", () => {
      const ch = +b.closest(".habit").dataset.ch;
      S.picks = S.picks.includes(ch) ? S.picks.filter((c) => c !== ch) : S.picks.concat(ch);
      redraw();
    }));
    $("#all").addEventListener("click", () => { S.picks = S.picks.length === all.length ? [] : all.slice(); redraw(); });
    $("#none").addEventListener("click", () => { S.picks = []; redraw(); });
    const up = $("#unplayed"); if (up) up.addEventListener("click", () => { S.picks = unplayed.slice(); redraw(); });
    $("#launch").addEventListener("click", launch);
  }

  // ---------- the moments: 2 per habit (1 each when more than 3 are picked), all from the other planet
  // A moment is {chapter, id}. The id (e.g. "3-venus-1") is the same in every language, so text is looked up by id, never by position.
  const sidePool = (ch) => idea(ch).scenarios.filter((s) => s.for === S.side).map((s) => ({ chapter: ch, id: s.id }));
  const scenario = (i, id) => tx(i).scenarios.find((s) => s.id === id) || i.scenarios.find((s) => s.id === id);
  function launch() {
    const k = perHabit();
    S.picks.sort((a, b) => a - b);
    const pool = S.picks.map((ch) => shuffle(sidePool(ch)).slice(0, k));
    S.deck = []; for (let r = 0; r < k; r++) for (const p of pool) if (p[r]) S.deck.push(p[r]);
    if (k === 1) S.deck = shuffle(S.deck);
    S.i = 0; S.score = Object.fromEntries(S.picks.map((c) => [c, { good: 0, n: 0 }]));
    app.classList.remove("compact"); next();
  }
  function next() {
    if (S.i >= S.deck.length) return debrief();
    const m = S.deck[S.i++], i = idea(m.chapter), w = tx(i), sc = scenario(i, m.id), flip = Math.random() < 0.5;
    const good = { text: sc.good, good: true }, miss = { text: sc.miss, good: false };
    step(T("moment.step", { i: S.i, n: S.deck.length })); setFace(them(), ["low", "calm", "quiet"][Math.floor(Math.random() * 3)]); setFace(me(), "calm");
    moment({ who: other(S.side), prompt: sc.prompt, label: w.name, cardIcon: i.icon, left: flip ? good : miss, right: flip ? miss : good,
      onPick: (o) => { const s = S.score[m.chapter]; s.n++; if (o.good) s.good++; reveal(m.chapter, o.good, next); } });
  }

  // ---------- results: score, one move for today, and the star map (readers' love vs research)
  const ratio = (s) => (s && s.n ? s.good / s.n : 0);
  function debrief() {
    step(T("res.step")); app.classList.add("compact"); setFace(P_EL.mars, "happy"); setFace(P_EL.venus, "happy");
    signal(T("res.done"), T("res.nice"));
    const total = Object.values(S.score).reduce((a, s) => a + s.n, 0), got = Object.values(S.score).reduce((a, s) => a + s.good, 0);
    const weakest = S.picks.slice().sort((a, b) => ratio(S.score[a]) - ratio(S.score[b]))[0];
    const I = S.content.ideas, gems = I.filter((i) => i.reader.score < 30 && i.light === "GREEN"), both = I.filter((i) => i.reader.score > 50 && i.light === "GREEN");
    panel.innerHTML = `
      <span class="label">${esc(T("res.label", { name: NAME(S.side) }))}</span>
      <div class="row spread"><div class="score">${got}/${total}</div><span class="label" style="text-align:right">${rich("res.stats", { km: S.orbit })}</span></div>
      <div class="bars">${S.picks.map((c) => `<div class="bar"><span>${esc(tx(idea(c)).name)}</span><span>${S.score[c].good}/${S.score[c].n}</span><i style="--w:${Math.round(ratio(S.score[c]) * 100)}%"></i></div>`).join("")}</div>
      <div class="move"><span class="label">${esc(T("res.today"))}</span><b>${esc(tx(idea(weakest)).actions[S.side])}</b></div>
      <span class="label">${esc(T("res.mapTitle"))}</span>
      ${starMap()}
      <div class="insight"><i class="dot GREEN" style="margin-top:6px"></i><span>${rich("res.both", { n: both.length })} <button class="link" data-receipt="${both[0].chapter}">${esc(tx(both[0]).name)}</button></span></div>
      <div class="insight"><i class="dot GREEN" style="margin-top:6px"></i><span>${rich("res.gems", { n: gems.length })}</span></div>
      <div class="row" style="margin-top:14px"><button class="btn solid" id="again">${esc(T("res.again"))}</button><button class="btn" id="share">${esc(T("res.share"))}</button></div>
      <p style="margin-top:12px"><a class="link" href="how.html${langQ}">${esc(T("how.link"))}</a></p>
      <p class="foot">${rich("res.foot", { reviews: S.content.reviewsRead, quotes: S.content.quotesChecked, date: S.content.readOn })}</p>`;
    panel.scrollTop = 0;
    panel.querySelectorAll(".star").forEach((s) => { s.addEventListener("click", () => openSheet(+s.dataset.ch, true)); s.addEventListener("keydown", (e) => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); openSheet(+s.dataset.ch, true); } }); });
    $("#again").addEventListener("click", start);
    $("#share").addEventListener("click", share);
  }
  function starMap() {
    const X = (x) => 34 + x * 270, Y = (y) => 214 - y * 192, lift = (i) => ((i.reader.rank % 3) - 1) * 12; // spread stars that share a light
    const col = { GREEN: "#69db7c", AMBER: "#ffc078", RED: "#ff6b6b", GREY: "#adb5bd" };
    const qx = X(50 / Math.max(...S.content.ideas.map((i) => i.reader.score))), qy = Y(0.68);
    const stars = S.content.ideas.map((i) => {
      const x = X(i.map.x), y = Y(i.map.y) + lift(i), gem = i.reader.score < 30 && i.light === "GREEN", mine = S.picks.includes(i.chapter);
      return `<g class="star" data-ch="${i.chapter}" tabindex="0" role="button" aria-label="${esc(T("map.starAria", { name: tx(i).name, rank: i.reader.rank, light: LIGHT(i.light) }))}">
        ${gem ? `<circle class="gem" cx="${x}" cy="${y}" r="11" fill="none" stroke="${col[i.light]}"/>` : ""}
        ${mine ? `<circle cx="${x}" cy="${y}" r="8" fill="none" stroke="#fff" stroke-dasharray="2 2"/>` : ""}
        <circle class="core" cx="${x}" cy="${y}" r="${3 + i.map.x * 3}" fill="${col[i.light]}" filter="url(#glow)"/>
        <text x="${x + 8}" y="${y + 3}" fill="rgba(255,255,255,.7)" font-size="8" letter-spacing="1">${i.chapter}</text></g>`;
    }).join("");
    return `<svg class="map" viewBox="0 0 320 250" role="img" aria-label="${esc(T("map.aria"))}">
      <defs><filter id="glow"><feGaussianBlur stdDeviation="2" result="b"/><feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge></filter></defs>
      <line x1="${qx}" y1="16" x2="${qx}" y2="220" stroke="rgba(255,255,255,.2)" stroke-dasharray="3 4"/>
      <line x1="30" y1="${qy}" x2="310" y2="${qy}" stroke="rgba(255,255,255,.2)" stroke-dasharray="3 4"/>
      <g fill="rgba(255,255,255,.45)" font-size="7.5" letter-spacing="1.4">
        <text x="36" y="26">${esc(T("map.gems"))}</text><text x="304" y="26" text-anchor="end">${esc(T("map.both"))}</text>
        <text x="36" y="212">${esc(T("map.skipped"))}</text><text x="304" y="212" text-anchor="end">${esc(T("map.loved"))}</text>
        <text x="170" y="242" text-anchor="middle">${esc(T("map.x"))}</text><text x="12" y="120" transform="rotate(-90 12 120)" text-anchor="middle">${esc(T("map.y"))}</text>
      </g>${stars}</svg>`;
  }

